export async function seedLocationPages() {
  console.log('[Location SEO Seed] Checking target location landing pages...');
  for (const p of LOCATION_SEO_PAGES) {
    try {
      const existing = await db.getCustomPageBySlug(p.slug);
      if (!existing) {
        await db.saveCustomPage(p);
        console.log(`[Location SEO Seed] Created target location page: ${p.slug}`);
      } else {
        // Ensure metaKeywords and H1 are updated
        await db.saveCustomPage({
          ...existing,
          metaKeywords: p.metaKeywords,
          metaTitle: p.metaTitle,
          metaDescription: p.metaDescription,
          title: p.title
        });
      }
    } catch (err) {
      console.error(`[Location SEO Seed] Failed seeding page ${p.slug}:`, err);
    }
  }
  console.log('[Location SEO Seed] Target location landing pages verified.');
}
